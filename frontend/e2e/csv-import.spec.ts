import { expect, test } from "@playwright/test";

test("imports one 100k CSV atomically and resolves an identical-file retry", async ({ page, baseURL }) => {
  test.skip(process.env.GENTUM_VERIFICATION_FIXTURE !== "1", "Requires disposable data");
  test.setTimeout(120000);
  let status = await page.request.get("/auth/status").then(r => r.json());
  const post = async (path: string, data: unknown) => {
    const response = await page.request.post(path, { data, headers: { Origin: baseURL!, "X-Gentum-Database": status.databaseId } });
    expect(response.ok(), await response.text()).toBe(true);
    const result = await response.json(); expect(result.errors).toBeUndefined(); return result;
  };
  if (status.setupRequired) await post("/auth/setup", { source: "new", mode: "open" });
  else if (!status.unlocked) await post("/auth/open", {});
  status = await page.request.get("/auth/status").then(r => r.json());
  const name = `CSV fixture ${Date.now()}`;
  await post("/databases/create", { name, mode: "open" });
  const registry = await page.request.get("/databases", { headers: { "X-Gentum-Database": status.databaseId } }).then(r => r.json());
  await post("/databases/select", { id: registry.databases.find((d: { name: string }) => d.name === name).id });
  status = await page.request.get("/auth/status").then(r => r.json());
  const gql = (query: string, variables = {}) => post("/graphql", { query, variables });
  const account = (await gql('mutation{createAccount(input:{name:"Current Account",type:CURRENT,currency:"EUR",initialBalance:"0"}){id}}')).data.createAccount.id;
  const summary = (await gql('{financeSummary(month:"2026-10")}')).data.financeSummary;
  const category = summary.categories.find((c: { name: string }) => c.name === "Wages").id;
  const csv = "date,kind,category_id,amount_cents,description\n" + `2026-10-01,INCOME,${category},1,Synthetic load test\n`.repeat(100000);
  await page.setViewportSize({ width: 1280, height: 850 });
  await page.goto("/");
  await page.getByRole("navigation").getByRole("button", { name: "Import & export", exact: true }).click();
  await page.getByLabel("Choose CSV file").setInputFiles({ name: "synthetic-100k.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByRole("button", { name: "Preview CSV", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Import preview: 100000 transactions" })).toBeVisible({ timeout: 40000 });
  await expect(page.getByRole("region", { name: "CSV preview" }).locator("tbody tr")).toHaveCount(50);
  await page.getByRole("button", { name: "Import CSV", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  await page.screenshot({ path: "/tmp/gentum-import-progress-1280.png" });
  await expect(dialog.getByRole("heading", { name: "Import complete" })).toBeVisible({ timeout: 60000 });
  await expect(dialog.getByRole("status")).toHaveText("Imported 100000 transactions");
  await page.screenshot({ path: "/tmp/gentum-import-complete-1280.png" });
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  const balance = async () => (await gql('{financeSummary(month:"2026-10")}')).data.financeSummary.accounts.find((a: { id: string }) => a.id === account).balance;
  expect(await balance()).toBe("100000");
  await page.getByRole("button", { name: "Preview CSV", exact: true }).click();
  await expect(page.getByRole("button", { name: "Import CSV", exact: true })).toBeEnabled({ timeout: 40000 });
  await page.getByRole("button", { name: "Import CSV", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "Import complete" })).toBeVisible({ timeout: 40000 });
  expect(await balance()).toBe("100000");
  await page.setViewportSize({ width: 800, height: 600 });
  await page.screenshot({ path: "/tmp/gentum-import-complete-800.png" });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
});
